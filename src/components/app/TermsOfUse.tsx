type TermsOfUseProps = {
  accepted: boolean;
  onAcceptedChange: (accepted: boolean) => void;
  variant?: "purple" | "yellow";
  checkboxLabel?: string;
};

export function TermsOfUse({
  accepted,
  onAcceptedChange,
  variant = "purple",
  checkboxLabel = "I have read, understood, and agree to the above Terms of Use, Consent and Waiver.",
}: TermsOfUseProps) {
  const [scrollBox, setScrollBox] = useState<HTMLDivElement | null>(null);

  const boxTheme =
    variant === "yellow"
      ? "border-yellow/30 bg-yellow/15 text-yellow-foreground"
      : "border-purple/30 bg-purple/15 text-purple-foreground";

  const checkboxTheme =
    variant === "yellow"
      ? "border-yellow-foreground/30 data-[state=checked]:bg-yellow data-[state=checked]:text-yellow-foreground"
      : "border-purple-foreground/30 data-[state=checked]:bg-purple data-[state=checked]:text-purple-foreground";

  return (
    <div className={`rounded-lg border p-4 ${boxTheme}`}>
      <h3 className="mb-2 text-sm font-semibold uppercase tracking-wide">
        Terms of Use, Consent and Waiver
      </h3>
      <div
        ref={setScrollBox}
        onScroll={() => {
          if (!scrollBox) return;
          const nearBottom =
            scrollBox.scrollHeight - scrollBox.scrollTop - scrollBox.clientHeight < 20;
          if (nearBottom && !accepted) onAcceptedChange(true);
        }}
        className="mb-4 max-h-60 overflow-y-auto rounded-md border border-black/5 bg-background/50 p-3 text-xs leading-relaxed"
      >
        <p className="mb-3 font-medium">
          By using this service, you agree to the following terms. Please read them carefully before proceeding.
        </p>
        {TERMS.map((term) => (
          <div key={term.title} className="mb-3">
            <p className="font-semibold">{term.title}</p>
            <p>{term.text}</p>
          </div>
        ))}
      </div>
      <div className="flex items-start gap-3">
        <Checkbox
          id="terms-of-use"
          checked={accepted}
          onCheckedChange={(checked) => onAcceptedChange(checked === true)}
          className={`mt-0.5 ${checkboxTheme}`}
        />
        <div className="grid gap-1.5 leading-none">
          <Label
            htmlFor="terms-of-use"
            className={`cursor-pointer text-sm font-medium ${
              variant === "yellow" ? "text-yellow-foreground" : "text-purple-foreground"
            }`}
          >
            {checkboxLabel}
          </Label>
        </div>
      </div>
    </div>
  );
}
